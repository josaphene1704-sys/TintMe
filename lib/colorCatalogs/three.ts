import type { ColorCatalog, ShadeTemperature } from "./types";

// גוונים ללא רמה "רגילה" — קוררקטורים, בוסטרים וטונר בלי בסיס צבע, מטופלים
// כיעד רמה 12 (מצריכים שיער מובהר מראש), באותה מוסכמה שקיימת ב-Igora
const SPECIAL_LEVEL_12_CODES = new Set([
  "900", "901", "903", "Booster", "biondo-svedese",
  "cenere", "blu", "rosso-extra", "giallo", "argento", "perla",
]);

// גלגל הצבעים של Three: ספרת הטון שאחרי הנקודה קובעת טמפרטורה (לפי הסמנטיקה
// של המותג הזה בלבד — אפור/סגול = קר, זהב/נחושת/מהגוני/אדום/טבעי = חם)
const COOL_CODES = new Set([
  "1B", "12.01", "12.91", "901", "biondo-svedese",
  "1.2", "4.2", "5.2", "6.2", "7.2",
  "cenere", "blu", "argento", "perla",
  "4.1", "5.1", "6.1", "7.1", "8.1", "9.1", "10.1",
  "6.31", "7.31", "8.31", "9.31",
]);
const NEUTRAL_CODES = new Set(["Booster"]);
const LEADING_LEVEL_DIGITS = /^(\d+)/;

function threeLevel(code: string): number {
  if (SPECIAL_LEVEL_12_CODES.has(code)) return 12;
  if (code === "1B") return 1;
  const m = code.match(LEADING_LEVEL_DIGITS);
  return m ? Number.parseInt(m[1], 10) : 0;
}

function threeTemperature(code: string): ShadeTemperature {
  if (NEUTRAL_CODES.has(code)) return "neutral";
  if (COOL_CODES.has(code)) return "cool";
  return "warm";
}

function shade(code: string, nameHe: string, nameAr: string, hex: string) {
  return { code, nameHe, nameAr, hex, level: threeLevel(code), temperature: threeTemperature(code) };
}

