import type { ColorCatalog, Shade, ShadeTemperature } from "./types";

// ─── סיווג רמה ────────────────────────────────────────────────────────────────
// גוונים ללא רמת בסיס משלהם — סילבר, אופנה ובוסטרים — דורשים שיער מובהר מראש
// (רמה 10–12), ולכן מטופלים כיעד רמה 12. אותה מוסכמה בדיוק כמו ב-three.ts,
// והערכים זהים ל-SILVER_CODES/FASHION_CODES/BOOSTER_CODES שב-page3.
const SILVER_CODES = ["slate-grey", "grey-lilac", "dove-grey", "silver"];
const FASHION_CODES = ["L-88", "L-89"];
const BOOSTER_CODES = ["0-99", "0-89", "0-33", "0-22", "0-11", "0-00"];
const SPECIAL_LEVEL_12_CODES = new Set([...SILVER_CODES, ...FASHION_CODES, ...BOOSTER_CODES]);

const LEADING_LEVEL = /^(\d+(?:\.\d+)?)/;

function igoraLevel(code: string): number {
  if (SPECIAL_LEVEL_12_CODES.has(code)) return 12;
  const m = code.match(LEADING_LEVEL);
  return m ? Number.parseFloat(m[1]) : 0;
}

// ─── סיווג טמפרטורה ───────────────────────────────────────────────────────────
// גלגל הצבעים של Igora: הספרה/ות אחרי המקף קובעות את הטון.
// 0 טבעי (חם), 1 אפרפר (קר), 2 פנינה (קר), 3 זהב (חם), 4 בז' (קר),
// 5 זהב (חם), 6 שוקולד (חם), 7 מהגוני (חם), 8 אדום (חם), 9 סגול (קר).
// שים לב שזו סמנטיקה שונה מ-Three, שם ספרת "4" היא נחושת/חם — ולכן כל קטלוג
// מחשב טמפרטורה בעצמו ואין להעתיק בין השניים.
const WARM_UNDERTONE_SUFFIXES = new Set(["0", "3", "5", "6", "7", "8", "50", "60", "70", "80", "710"]);
const COOL_UNDERTONE_SUFFIXES = new Set(["1", "11", "2", "19", "21", "22", "4", "12", "14", "46"]);
// סילבר/מנטרלים קרים בבירור, אבל אין להם סיומת מספרית לפרסר
const COOL_NAMED_CODES = new Set([...SILVER_CODES, "0-99", "0-22", "0-11"]);

function igoraTemperature(code: string): ShadeTemperature {
  if (COOL_NAMED_CODES.has(code)) return "cool";
  if (code === "0-00") return "neutral";
  const suffix = code.split("-")[1];
  if (!suffix) return "neutral";
  if (WARM_UNDERTONE_SUFFIXES.has(suffix)) return "warm";
  if (COOL_UNDERTONE_SUFFIXES.has(suffix)) return "cool";
  return "neutral";
}

function shade(code: string, nameHe: string, nameAr: string, hex: string): Shade {
  return { code, nameHe, nameAr, hex, level: igoraLevel(code), temperature: igoraTemperature(code) };
}

